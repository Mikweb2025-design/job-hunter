_ATTR = re.compile(r'(\b(?:title|placeholder|aria-label|alt)=")([^"]*)(")')
_BLOCKS = re.compile(r"(<script\b.*?</script>|<style\b.*?</style>)", re.S | re.I)
_TEXT = re.compile(r">([^<>]+)<")
_MIN_SUB = 14      # shorter phrases only replace a whole text node


def _tables(lang: str):
    idx = {"en": 1, "it": 2}[lang]
    exact: dict[str, str] = {}
    sub: list[tuple[str, str]] = []
    for row in PHRASES:
        de, tr = row[0], row[idx]
        exact[" ".join(de.split())] = tr
        if len(de) >= _MIN_SUB:
            sub.append((de, tr))
    sub.sort(key=lambda p: -len(p[0]))
    return exact, sub


_CACHE: dict[str, tuple] = {}


def _tr_text(raw: str, exact: dict, sub: list, unescape: bool) -> str:
    text = _html.unescape(raw) if unescape else raw
    norm = " ".join(text.split())
    if not norm:
        return raw
    if norm in exact:
        lead = text[: len(text) - len(text.lstrip())]
        trail = text[len(text.rstrip()):]
        out = lead + exact[norm] + trail
    else:
        out, changed = text, False
        for de, tr in sub:
            if de in out:
                out = out.replace(de, tr)
                changed = True
        if not changed:
            return raw
    return _html.escape(out, quote=False) if unescape else out


def translate_html(page: str, lang: str) -> str:
    if lang not in ("en", "it"):
        return page
    exact, sub = _CACHE.setdefault(lang, _tables(lang))
    parts = _BLOCKS.split(page)
    for i in range(0, len(parts), 2):          # odd parts are <script>/<style>
        seg = parts[i]
        seg = _TEXT.sub(lambda m: ">" + _tr_text(m.group(1), exact, sub, True) + "<", seg)
        seg = _ATTR.sub(lambda m: m.group(1) + _tr_text(m.group(2), exact, sub, False) + m.group(3), seg)
        parts[i] = seg
    return "".join(parts)
